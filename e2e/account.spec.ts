import { expect, test } from '@playwright/test'
import { boot, login } from './helpers'

test('cadastro, conflito, sessão e troca de usuário', async ({ page }) => {
  await boot(page, 'register-conflict')
  await page.goto('/cadastro')
  const form = page.locator('form')
  await form.getByLabel('Nome de usuário').fill('luna')
  await form.getByLabel('E-mail', { exact: true }).fill('luna@kurio.test')
  await form.getByLabel('Senha', { exact: true }).fill('Kurio#2026')
  await form.getByLabel('Confirmar senha').fill('Kurio#2026')
  await page.getByRole('button', { name: 'Criar perfil' }).click()
  await expect(page.getByRole('alert')).toContainText('Este e-mail já está em uso.')

  await boot(page)
  await page.goto('/cadastro')
  const signup = page.locator('form')
  await signup.getByLabel('Nome de usuário').fill('luna')
  await signup.getByLabel('E-mail', { exact: true }).fill('luna@kurio.test')
  await signup.getByLabel('Senha', { exact: true }).fill('Kurio#2026')
  await signup.getByLabel('Confirmar senha').fill('diferente')
  await page.getByRole('button', { name: 'Criar perfil' }).click()
  await expect(page.getByRole('alert')).toContainText('As senhas não conferem.')
  await signup.getByLabel('Confirmar senha').fill('Kurio#2026')
  await page.getByRole('button', { name: 'Criar perfil' }).click()
  await expect(page.getByRole('button', { name: 'luna' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'luna' })).toBeVisible()

  await page.getByRole('button', { name: 'luna' }).click()
  await page.getByRole('menuitem', { name: 'Sair' }).click()
  await expect(page.getByRole('link', { name: 'Entrar' })).toBeVisible()

  await login(page, 'ada@kurio.test')
  await page.goto('/carrinho')
  await expect(page.getByRole('heading', { name: 'Golden Beat #0207' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Sage Nomad #0009' })).toHaveCount(0)
})

test('sessão expirada devolve ao login com o destino', async ({ page }) => {
  await boot(page)
  await login(page)
  await boot(page, 'session-expired')
  await page.goto('/conta/perfil')
  await expect(page).toHaveURL(/\/entrar/)
  await expect(page.getByText(/sessão expirou/i)).toBeVisible()
})

test('perfil, senha e carteiras permanecem após atualizar', async ({ page }) => {
  await boot(page)
  await login(page)
  await page.goto('/conta/perfil')
  await page.getByLabel('Nome de exibição').fill('Nova Ateliê')
  await page.getByRole('button', { name: 'Salvar' }).first().click()
  await expect(page.getByText('Perfil atualizado.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Nome de exibição')).toHaveValue('Nova Ateliê')

  await page.getByLabel('Senha atual *').fill('errada')
  await page.getByLabel('Nova senha *', { exact: true }).fill('Kurio#2027')
  await page.getByLabel('Confirmar nova senha *').fill('Kurio#2027')
  await page.getByRole('button', { name: 'Salvar' }).nth(1).click()
  await expect(page.getByRole('alert').first()).toBeVisible()
  await page.getByLabel('Senha atual *').fill('Kurio#2026')
  await page.getByRole('button', { name: 'Salvar' }).nth(1).click()
  await expect(page.getByText('Senha alterada.')).toBeVisible()

  await page.goto('/conta/carteiras')
  await expect(page.getByLabel('Endereço da carteira').first()).toHaveValue(/0xA91F/)
  await page.getByLabel('Apelido da carteira').first().fill('Ateliê')
  await page.getByRole('button', { name: 'Salvar carteira' }).first().click()
  await expect(page.getByText('Carteira salva.')).toBeVisible()
  await page.getByLabel('Endereço da carteira').nth(1).fill('curto')
  await page.getByRole('button', { name: 'Salvar carteira' }).nth(1).click()
  await expect(page.getByRole('alert').first()).toContainText('Endereço inválido.')
  await page.reload()
  await expect(page.getByLabel('Apelido da carteira').first()).toHaveValue('Ateliê')
})

