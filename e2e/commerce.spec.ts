import { expect, test } from '@playwright/test'
import { boot, confirmPurchase, login } from './helpers'

test('carrinho, cupom e compra até o recibo', async ({ page }) => {
  await boot(page)
  await page.goto('/nfts/emerald-ape-0042')
  await page.getByRole('button', { name: 'COMPRAR', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Emerald Ape #0042' }).last()).toBeVisible()
  await page.getByRole('button', { name: 'Aumentar Emerald Ape #0042' }).click()
  await expect(page.getByText('2.38 ETH').first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Emerald Ape #0042' }).last()).toBeVisible()
  await page.getByLabel('Código promocional').fill('KURIO10')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.getByText('0.238 ETH').first()).toBeVisible()
  await page.getByLabel('Código promocional').fill('NAOEXISTE')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.getByRole('alert')).toContainText('Cupom inválido.')
  await page.getByLabel('Código promocional').fill('VENCIDO')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.getByRole('alert')).toContainText('Cupom expirado.')
  await page.getByRole('button', { name: 'Remover Emerald Ape #0042' }).click()
  await expect(page.getByText('Seu carrinho está vazio.')).toBeVisible()

  await login(page)
  await page.goto('/carrinho')
  await expect(page.getByRole('heading', { name: 'Sage Nomad #0009' })).toBeVisible()
  await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  await page.getByRole('button', { name: 'Simular recusa' }).click()
  await expect(page.getByText('A carteira recusou a conexão.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeDisabled()
  await page.getByRole('button', { name: 'Desconectar' }).click()
  await confirmPurchase(page)
  const tx = await page.getByText(/0x[a-f0-9]+E82C/i).textContent()
  await page.reload()
  await expect(page.getByText('THANK YOU')).toBeVisible()
  await expect(page.getByText(tx ?? '')).toBeVisible()
  await page.getByRole('link', { name: 'Ver no Etherscan' }).click()
  await expect(page.getByRole('heading', { name: 'Transação' })).toBeVisible()
  await page.goto('/carrinho')
  await expect(page.getByText('Seu carrinho está vazio.')).toBeVisible()
})

